export type ExamPeriod = "1교시" | "2교시";

/** 참고자료(교재/서브노트 발췌)가 있으면 최우선 근거로 사용하도록 지시하는 블록. */
function refBlock(reference?: string): string[] {
  if (!reference?.trim()) return [];
  return [
    ``,
    `[참고자료 — 내 교재/서브노트 (★최우선 정답 근거★)]`,
    reference.trim(),
    `※ 매우 중요: 위 참고자료가 곧 정답이다. 참고자료에 항목/목록(예: Top 10 항목, 구성요소)이 나열돼 있으면 반드시 "그 항목 그대로"만 사용하라. 모델 자체 지식으로 항목을 바꾸거나, 없는 항목을 추가·창작하지 말 것. 참고자료와 다른 내용을 쓰면 오답이다.`,
    ``,
  ];
}

