/**
 * 정보관리기술사 시험 특성에 맞춘 프롬프트 템플릿 모음.
 *
 * 시험 구성 요약:
 *  - 1교시: 용어형 단답. 13문제 중 10문제 선택, 문제당 10점. 답안 약 1페이지(1~1.5쪽).
 *  - 2~4교시: 서술형. 6문제 중 4문제 선택, 문제당 25점. 답안 약 2~3페이지.
 *    개요(정의/배경) → 본론(구성도/메커니즘/특징/비교표 등) → 결론(고려사항/전망) 구조.
 */

export const TUTOR_SYSTEM =
  "당신은 대한민국 정보관리기술사 시험을 20년간 지도한 전문 멘토입니다. " +
  "항상 한국어로, 정확하고 시험에 최적화된 형태로 답변합니다. " +
  "표·도식(텍스트 다이어그램)·키워드를 적극 활용하고, 최신 기술 동향과 실무 사례를 반영합니다.";

export type ExamPeriod = "1교시" | "2교시";

export function answerPrompt(period: ExamPeriod, question: string): string {
  if (period === "1교시") {
    return [
      `다음은 정보관리기술사 1교시(용어형 단답) 문제입니다. 실제 시험 답안지 형식으로 작성하세요.`,
      ``,
      `[문제]`,
      question,
      ``,
      `[작성 지침]`,
      `- 분량: 1페이지 내외(약 600~900자). 핵심만 압축.`,
      `- 구조를 마크다운으로 명확히 구분:`,
      `  ## 1. 정의 (한 문장으로 핵심 정의)`,
      `  ## 2. 개념도 / 구성요소 (텍스트 도식 또는 표)`,
      `  ## 3. 특징 / 동작원리 (3~5가지, 표 권장)`,
      `  ## 4. 활용 및 고려사항`,
      `- 두문자어·핵심 키워드는 **굵게** 표시.`,
      `- 채점자가 한눈에 파악하도록 항목화하세요.`,
    ].join("\n");
  }
  return [
    `다음은 정보관리기술사 2교시 이상(서술형) 문제입니다. 실제 시험 답안지 형식으로 작성하세요.`,
    ``,
    `[문제]`,
    question,
    ``,
    `[작성 지침]`,
    `- 분량: 2~3페이지 수준으로 충실하게(약 1500~2500자).`,
    `- 답안 구조를 마크다운으로 작성:`,
    `  # I. 개요`,
    `     - 정의와 등장 배경을 서술`,
    `  # II. (핵심 주제) 의 구성도 및 구성요소`,
    `     - 텍스트 기반 아키텍처/흐름 도식 + 구성요소 설명 표`,
    `  # III. (핵심 주제) 의 상세 메커니즘 / 특징`,
    `     - 동작 원리, 단계, 비교표 등`,
    `  # IV. 적용 시 고려사항 및 기대효과`,
    `  # V. 결론`,
    `- 표(| ... |)와 텍스트 다이어그램을 반드시 1개 이상 포함.`,
    `- 핵심 키워드는 **굵게**, 두문자어는 풀어서 한 번 설명.`,
    `- 기술사 수준의 깊이(트레이드오프, 실무 적용)를 보여주세요.`,
  ].join("\n");
}

export function explainPrompt(topic: string, level: string): string {
  return [
    `정보관리기술사 수험생에게 아래 토픽을 "${level}" 눈높이로 이해하기 쉽게 설명하세요.`,
    ``,
    `[토픽]`,
    topic,
    ``,
    `[작성 지침]`,
    `- 먼저 일상 비유로 직관적으로 설명한 뒤, 정확한 기술적 정의로 연결.`,
    `- 다음 구조(마크다운):`,
    `  ## 한 줄 요약`,
    `  ## 쉬운 비유로 이해하기`,
    `  ## 핵심 개념 (필요시 표/도식)`,
    `  ## 왜 중요한가 / 어디에 쓰이나`,
    `  ## 시험 포인트 (자주 출제되는 부분, 연관 키워드)`,
    `- 어려운 용어는 괄호로 풀어서 설명.`,
  ].join("\n");
}

export function flashcardPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 플래시카드를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 앞면(front): 핵심 질문 또는 용어.`,
    `- 뒷면(back): 시험 답안 수준의 간결하고 정확한 설명(2~4문장).`,
    `- 토픽의 중요 개념을 고르게 다룰 것.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"front":"질문/용어","back":"답"}]`,
  ].join("\n");
}

export function quizPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 4지선다 객관식 퀴즈를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 각 문제는 보기 4개(options), 정답 인덱스(answer, 0~3), 해설(explanation) 포함.`,
    `- 난이도는 기술사 수준으로, 헷갈리는 오답을 포함.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"question":"문제","options":["a","b","c","d"],"answer":0,"explanation":"해설"}]`,
  ].join("\n");
}
