/** 답안 작성 힌트: 핵심 키워드 + 두음신공 + 목차 제안(직접 작성을 돕는 용도). */
export function hintPrompt(period: ExamPeriod, question: string): string {
  return [
    `정보관리기술사 ${period} 문제에 대해, 수험생이 직접 답안을 쓸 수 있도록 "힌트"만 제공하세요. (완성 답안 작성 금지)`,
    ``,
    `[문제]`,
    question,
    ``,
    `[제공할 힌트]`,
    `- keywords: 답안에 반드시 포함해야 할 핵심 키워드 5~8개.`,
    `- mnemonic: 그 키워드(또는 핵심 구성요소)의 첫 글자를 모은 두음신공(외우기 쉬운 문장/단어).`,
    `- mnemonicHow: 두음 연상법 1줄.`,
    `- outline: ${period} 방법론에 맞는 답안 목차 제안(제목만, 3~4개).`,
    ``,
    `[출력 형식] 반드시 아래 JSON 객체만 출력(설명·코드블록 텍스트 금지):`,
    `{"keywords":["키워드1","키워드2"],"mnemonic":"두음 문장","mnemonicHow":"연상법","outline":["I. ...","II. ...","III. ..."]}`,
  ].join("\n");
}
