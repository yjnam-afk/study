export type ExamPeriod = "1교시" | "2교시";

export function answerPrompt(period: ExamPeriod, question: string): string {
  if (period === "1교시") {
    return [
      `다음은 정보관리기술사 1교시(용어형 단답) 문제입니다. ITPE 실전 방법론에 따라 답안지 형식으로 작성하세요.`,
      ``,
      `[문제]`,
      question,
      ``,
      `[1교시 답안 구조 — 3단락 / 약 1~1.4페이지]`,
      `먼저 맨 윗줄에 "문) (토픽 Full Name) 요약" 형태의 리드문을 1줄 작성.`,
      ``,
      `## I. (토픽)의 개념`,
      `   - 정의 2줄 (핵심만, 근거 포함)`,
      `   - 특징 1줄 (핵심 키워드 중심)`,
      ``,
      `## II. (토픽)의 개념도 및 구성요소`,
      `   - 텍스트 개념도/구성도(약 6줄 분량) 작성`,
      `   - 도식 아래 "간글" 1줄 부연`,
      `   - 3단표로 구성요소 정리: | 구분 | 구성요소 | 설명 |`,
      ``,
      `## III. (토픽)의 활용 / 고려사항 (차별화)`,
      `   - 적용 사례, 비교, 타 토픽 연계 등 깊이 있는 차별화 내용(7~8점 요소)`,
      ``,
      `[지침]`,
      `- 비교를 묻는 문제면 II에서 "비교표"(| 구분 | 개념A | 개념B |)를 사용.`,
      `- 핵심 키워드 **굵게**, 중요 용어 "큰따옴표", 두문자어는 풀어서 설명.`,
    ].join("\n");
  }
  return [
    `다음은 정보관리기술사 2~4교시(서술형) 문제입니다. ITPE 실전 방법론(IV단락 구조)에 따라 답안지 형식으로 작성하세요.`,
    ``,
    `[문제]`,
    question,
    ``,
    `[2교시 답안 구조 — 4단락 / 약 3~3.5페이지]`,
    `맨 윗줄에 "문) 문제 요약(물어본 것 나열)" 리드문을 1~2줄 작성(요구사항 누락 금지).`,
    ``,
    `# I. 서론 (약 0.5페이지)`,
    `   - 아래 6가지 서론 타입 중 문제에 가장 적합한 것을 선택해 도입:`,
    `     · Type I 1교시 상속/확장: 정의 2줄 + 특징(표)`,
    `     · Type II 정의+특징을 그림/도식으로(간글에 정의)`,
    `     · Type III Why관점: 중요성·필요성 강조(정의는 그림 밑 2줄 옵션)`,
    `     · Type IV 로드맵: 물어본 가·나·다를 하나의 개념도(6~7줄)로 표현 후 Top-down`,
    `     · Type V 병렬식: 답이 명확한 다항(가·나·다) 문제는 나열식 목차`,
    `     · Type VI 발전단계: 순서·절차·기술 발전과정이 있는 문제`,
    ``,
    `# II. 본론1 — (물어본 요구사항 그대로 목차화) (약 1페이지)`,
    `   - 요구사항이 없으면 기본 구성: 구성도 + 구성요소/기술요소 표`,
    ``,
    `# III. 본론2 — (물어본 요구사항 그대로 목차화) (약 1페이지)`,
    `   - 물어본 내용 중심으로 충실히(물어본 것이 안 물어본 것보다 많아야 함). 동작원리/단계/비교표 등`,
    ``,
    `# IV. 결론 및 고려사항(+α 차별화) (약 0.5페이지)`,
    `   - 적용 시 고려사항, 기대효과, 최신 동향·타 토픽 응용 등 차별화 "알파"(17점 요소)`,
    ``,
    `[지침]`,
    `- 표(| ... |)와 텍스트 개념도를 반드시 1개 이상 포함하고, 표·그림 아래 간글 부연.`,
    `- 물어본 항목(가·나·다)을 목차 제목에 그대로 노출(누락=감점).`,
    `- 핵심 키워드 **굵게**, 중요 용어 "큰따옴표", 두문자어는 풀어서 설명.`,
    `- 보통 2~3개 토픽이 융합되도록 깊이 있게, 트레이드오프·실무 적용을 보여줄 것.`,
  ].join("\n");
}

export function gradePrompt(
  period: ExamPeriod,
  question: string,
  userAnswer: string,
): string {
  const max = period === "1교시" ? 10 : 25;
  return [
    `다음은 정보관리기술사 ${period} 문제와 수험생이 작성한 답안입니다.`,
    `당신은 실제 채점위원입니다. ITPE 실전 답안 작성 방법론을 기준으로 엄격하지만 건설적으로 채점하세요.`,
    ``,
    `[문제]`,
    question,
    ``,
    `[수험생 답안]`,
    userAnswer,
    ``,
    `[채점 기준 — 방법론 항목별로 평가]`,
    `1. 리드문/문제 이해: 물어본 것을 빠짐없이 반영했는가(요구사항 누락 시 감점).`,
    `2. 목차 구성: 물어본 것을 목차 제목에 그대로 노출했는가.`,
    `3. 정의/개념: 핵심을 2줄 내외로 근거 있게 서술했는가.`,
    `4. 표·도식 활용: 3단표/개념도와 표·그림 하단 "간글"이 있는가.`,
    `5. 차별화(+α): 최신 동향·실무 사례·트레이드오프 등 고득점 요소가 있는가.`,
    `6. 분량/형식: ${period} 기준 분량과 항목화가 적절한가.`,
    ``,
    `[출력 형식 — 마크다운, 아래 구조를 그대로 사용]`,
    `## 총평`,
    `   - 2~3줄로 전체 인상과 합격 가능성 코멘트.`,
    `## 항목별 점수`,
    `   - | 평가 항목 | 배점 | 획득 | 코멘트 | 형식의 3단표(6개 항목).`,
    `   - 표 아래에 **총점: NN / ${max}점** 을 굵게 표기.`,
    `## 잘한 점`,
    `   - 구체적으로 2~3가지.`,
    `## 보완할 점 (감점 요인)`,
    `   - 방법론 기준으로 무엇이 빠졌는지 구체적으로, 어떻게 고치면 되는지까지.`,
    `## 개선 방향 한 줄 요약`,
    `   - 다음에 이 유형을 만나면 무엇을 가장 먼저 챙길지.`,
  ].join("\n");
}

export function explainPrompt(topic: string, level: string): string {
  return [
    `정보관리기술사 수험생에게 아래 토픽을 "${level}" 눈높이로 이해하기 쉽게 설명하세요.`,
    ``,
    `[토픽]`,
    topic,
    ``,
    `[작성 지침]`,
    `- 먼저 일상 비유로 직관적으로 설명한 뒤, 정확한 기술적 정의로 연결.`,
    `- 다음 구조(마크다운):`,
    `  ## 한 줄 요약`,
    `  ## 쉬운 비유로 이해하기`,
    `  ## 핵심 개념 (필요시 표/도식)`,
    `  ## 왜 중요한가 / 어디에 쓰이나`,
    `  ## 시험 포인트 (자주 출제되는 부분, 연관 키워드)`,
    `- 어려운 용어는 괄호로 풀어서 설명.`,
  ].join("\n");
}

export function flashcardPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 플래시카드를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 앞면(front): 핵심 질문 또는 용어.`,
    `- 뒷면(back): 시험 답안 수준의 간결하고 정확한 설명(2~4문장).`,
    `- 토픽의 중요 개념을 고르게 다룰 것.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"front":"질문/용어","back":"답"}]`,
  ].join("\n");
}

export function quizPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 4지선다 객관식 퀴즈를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 각 문제는 보기 4개(options), 정답 인덱스(answer, 0~3), 해설(explanation) 포함.`,
    `- 난이도는 기술사 수준으로, 헷갈리는 오답을 포함.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"question":"문제","options":["a","b","c","d"],"answer":0,"explanation":"해설"}]`,
  ].join("\n");
}
