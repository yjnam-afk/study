export function gradePrompt(
  period: ExamPeriod,
  question: string,
  userAnswer: string,
  reference?: string,
): string {
  const max = period === "1교시" ? 10 : 25;
  return [
    `다음은 정보관리기술사 ${period} 문제와 수험생이 작성한 답안입니다.`,
    `당신은 실제 채점위원입니다. ITPE 실전 답안 작성 방법론을 기준으로 엄격하지만 건설적으로 채점하세요.`,
    ``,
    `[문제]`,
    question,
    ...(reference?.trim()
      ? [
          ``,
          `[정답 근거 — 내 교재/서브노트 발췌]`,
          reference.trim(),
          `※ 정확도(사실 오류·누락)는 위 교재 내용을 정답 근거로 삼아 판단하고, 답안이 교재와 어긋나면 구체적으로 지적하세요.`,
        ]
      : []),
    ``,
    `[수험생 답안]`,
    userAnswer,
    ``,
    `[채점 기준 — ITPE 방법론 항목별로 평가]`,
    `1. (최우선) 출제 의도 적합: 물어본 것을 정확히, 빠짐없이 답했는가. 의도를 벗어났으면 0점에 가깝게 처리.`,
    `2. 리드문/요약: 맨 앞에 "문 N)" 요약과 요구사항 반영(누락 시 감점).`,
    `3. 목차 = 지문 그대로: 물어본 항목(가·나·다)을 지문 표현 그대로 목차에 노출했는가.`,
    `4. 정의: 키워드 나열식 2줄로 근거 있게 작성했는가(주저리/추상 나열 감점).`,
    `5. 일도일표: 텍스트 개념도 1개 + 3단표 1개와 표·그림 하단 간글이 있는가.`,
    `6. 차별화(+α): 최신 동향·실무/경험 사례·타 토픽 융합 등 고득점 요소가 있는가.`,
    period === "1교시"
      ? `7. 분량/형식: 1.2~1.4페이지·3단락(I·II·III), 사실 중심으로 적절한가.`
      : `7. 분량/형식: 3~3.5페이지·4단락(I~IV), 서론 6타입 중 적합한 선택과 단락 구성이 적절한가.`,
    period === "1교시"
      ? `[점수 밴드] 6점=의도 적합+정의 정확+III단락+1.2P / 7점 이상=키워드 다수+1.4P+남보다 우수.`
      : `[점수 밴드] 15점=의도 적합+물어본 것 1P / 16점=충분·정확+키워드 노출+3P↑ / 17점=차별화(알파) 깊이 추가.`,
    ``,
    `[출력 형식 — 마크다운, 아래 구조를 그대로 사용]`,
    `## 총평`,
    `   - 2~3줄로 전체 인상과 합격 가능성 코멘트.`,
    `## 항목별 점수`,
    `   - | 평가 항목 | 배점 | 획득 | 코멘트 | 형식의 3단표(6개 항목).`,
    `   - 표 아래에 **총점: NN / ${max}점** 을 굵게 표기.`,
    `## 잘한 점`,
    `   - 구체적으로 2~3가지.`,
    `## 보완할 점 (감점 요인)`,
    `   - 방법론 기준으로 무엇이 빠졌는지 구체적으로, 어떻게 고치면 되는지까지.`,
    `## 개선 방향 한 줄 요약`,
    `   - 다음에 이 유형을 만나면 무엇을 가장 먼저 챙길지.`,
  ].join("\n");
}

export function explainPrompt(topic: string, level: string): string {
  return [
    `정보관리기술사 수험생에게 아래 토픽을 "${level}" 눈높이로 이해하기 쉽게 설명하세요.`,
    ``,
    `[토픽]`,
    topic,
    ``,
    `[작성 지침]`,
    `- 먼저 일상 비유로 직관적으로 설명한 뒤, 정확한 기술적 정의로 연결.`,
    `- 다음 구조(마크다운):`,
    `  ## 한 줄 요약`,
    `  ## 쉬운 비유로 이해하기`,
    `  ## 핵심 개념 (필요시 표/도식)`,
    `  ## 왜 중요한가 / 어디에 쓰이나`,
    `  ## 시험 포인트 (자주 출제되는 부분, 연관 키워드)`,
    `- 어려운 용어는 괄호로 풀어서 설명.`,
  ].join("\n");
}

export function flashcardPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 플래시카드를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 앞면(front): 핵심 질문 또는 용어.`,
    `- 뒷면(back): 시험 답안 수준의 간결하고 정확한 설명(2~4문장).`,
    `- 토픽의 중요 개념을 고르게 다룰 것.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"front":"질문/용어","back":"답"}]`,
  ].join("\n");
}

export function quizPrompt(topic: string, count: number): string {
  return [
    `정보관리기술사 학습용 4지선다 객관식 퀴즈를 ${count}개 생성하세요. 토픽: "${topic}".`,
    ``,
    `[요구사항]`,
    `- 각 문제는 보기 4개(options), 정답 인덱스(answer, 0~3), 해설(explanation) 포함.`,
    `- 난이도는 기술사 수준으로, 헷갈리는 오답을 포함.`,
    ``,
    `[출력 형식] 반드시 아래 JSON 배열만 출력(설명·코드블록 텍스트 금지):`,
    `[{"question":"문제","options":["a","b","c","d"],"answer":0,"explanation":"해설"}]`,
  ].join("\n");
}

/**
 * 두음신공(頭音神功): 외워야 할 핵심 키워드들의 첫 글자(두음)를 모아
 * 외우기 쉬운 문장/단어로 만드는 한국 기술사 시험 암기법.
 * 객관식으로 "주입"하고 주관식으로 "확인"하는 데이터를 함께 생성한다.
 */
export function mnemonicPrompt(topic: string): string {
  return [
    `정보관리기술사 토픽 "${topic}"의 핵심 암기를 위한 "두음신공"(두문자 암기법) 학습 세트를 만드세요.`,
    ``,
    `[두음신공이란]`,
    `- 토픽에서 반드시 외워야 할 핵심 항목(구성요소·원칙·특징·절차 등) 4~7개를 선정.`,
    `- 각 항목의 첫 글자(두음)를 뽑아, 외우기 쉽고 연상되는 짧은 문장 또는 단어로 결합.`,
    `- 예) 트랜잭션 ACID(원자성·일관성·고립성·지속성) → 두음 "원일고지".`,
    ``,
    `[생성 규칙]`,
    `- items: 외울 핵심 항목 4~7개. 각 항목은 term(키워드), initial(term의 첫 글자), desc(한 줄 설명).`,
    `- mnemonic: items의 initial들을 모아 만든 외우기 쉬운 문장/단어(두음신공).`,
    `- mnemonicHow: 그 두음을 어떻게 연상해서 외우는지 1~2줄.`,
    `- mc(주입용 객관식 3개): 키워드/두음을 각인시키는 4지선다. options 4개, answer(0~3), explanation.`,
    `- recall(주관식 확인): prompt(두음을 보여주고 핵심 키워드를 모두 쓰라는 문제), answers(정답 키워드 배열 = items의 term들).`,
    ``,
    `[출력 형식] 반드시 아래 JSON 객체만 출력(설명·코드블록 텍스트 금지):`,
    `{"topic":"${topic}","items":[{"term":"키워드","initial":"키","desc":"설명"}],"mnemonic":"두음 문장","mnemonicHow":"연상법","mc":[{"question":"문제","options":["a","b","c","d"],"answer":0,"explanation":"해설"}],"recall":{"prompt":"두음 '○○○'이 의미하는 핵심 키워드를 모두 쓰시오.","answers":["키워드1","키워드2"]}}`,
  ].join("\n");
}

/**
 * "답안 소설 쓰는 법": 잘 모르는 토픽도 방법론 틀로 분량을 채워 그럴듯하게
 * 작성하는 실전 기술을 해당 문제에 맞춰 코칭한다(마크다운).
 */
export function storyPrompt(period: ExamPeriod, question: string): string {
  return [
    `정보관리기술사 ${period} 문제에 대해, 수험생이 토픽을 깊이 몰라도 방법론만으로 답안을 "소설처럼" 끝까지 채워 쓰는 법을 코칭하세요.`,
    `완성된 모범답안이 아니라, 스스로 분량을 채워 쓰도록 돕는 "작법 가이드 + 빈칸 채우기 템플릿"을 제시합니다.`,
    ``,
    `[문제]`,
    question,
    ``,
    `[작성 지침 — 마크다운, 아래 구조]`,
    `## 소설 공식 (만능 틀)`,
    `   - 이 유형에 쓸 단락 골격을 ${period} 방법론으로 제시(리드문→정의→구성/도식→동작·비교→고려사항·결론).`,
    `## 이 문제에 적용하기`,
    `   - 위 골격을 이 문제에 맞춰 어떤 목차로 잡을지 구체적으로.`,
    `## 단락별 "살 붙이기" 문장 템플릿`,
    `   - 빈칸([ ])이 있는 재사용 문장 템플릿을 단락별로 제시(정의/구성요소/동작원리/장단점/고려사항).`,
    `   - 일반 원리(가용성·확장성·보안·표준화·자동화·트레이드오프 등)로 분량을 늘리는 만능 표현 예시.`,
    `## 분량·시간 채우기 팁`,
    `   - 표·개념도·간글·차별화(+α)로 페이지를 채우는 요령.`,
    `## 주의 (감점·리스크)`,
    `   - 모르는 사실을 단정하지 말고 일반 원리로 서술할 것 등, 소설이 들통나지 않게 하는 주의점.`,
  ].join("\n");
}

/** 답안 작성 힌트: 핵심 키워드 + 두음신공 + 목차 제안(직접 작성을 돕는 용도). */
export function hintPrompt(period: ExamPeriod, question: string): string {
  return [
    `정보관리기술사 ${period} 문제에 대해, 수험생이 직접 답안을 쓸 수 있도록 "힌트"만 제공하세요. (완성 답안 작성 금지)`,
    ``,
    `[문제]`,
    question,
    ``,
    `[제공할 힌트]`,
    `- keywords: 답안에 반드시 포함해야 할 핵심 키워드 5~8개.`,
    `- mnemonic: 그 키워드(또는 핵심 구성요소)의 첫 글자를 모은 두음신공(외우기 쉬운 문장/단어).`,
    `- mnemonicHow: 두음 연상법 1줄.`,
    `- outline: ${period} 방법론에 맞는 답안 목차 제안(제목만, 3~4개).`,
    ``,
    `[출력 형식] 반드시 아래 JSON 객체만 출력(설명·코드블록 텍스트 금지):`,
    `{"keywords":["키워드1","키워드2"],"mnemonic":"두음 문장","mnemonicHow":"연상법","outline":["I. ...","II. ...","III. ..."]}`,
  ].join("\n");
}
